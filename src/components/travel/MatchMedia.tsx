"use client";

import type { MediaItem } from "@/lib/content/media";
import { Gallery } from "./Gallery";
import { Lightbox, useLightbox } from "./Lightbox";

/** One game's photos (swipeable) and clips, opening full size in the lightbox. */
export function MatchMedia({ media, label, priority = false }: { media: MediaItem[]; label: string; priority?: boolean }) {
  const lb = useLightbox();
  const photos = media.filter((m) => m.type === "photo");
  const clips = media.filter((m) => m.type === "video");
  return (
    <>
      {photos.length ? <Gallery photos={photos} label={`Photos: ${label}`} onOpen={(i) => lb.open(photos, i)} priority={priority} /> : null}
      {clips.length ? (
        <div className="clips" role="group" aria-label={`${clips.length} ${clips.length === 1 ? "clip" : "clips"}: ${label}`}>
          {clips.map((clip, i) => (
            <button key={clip.id} type="button" data-track="clip: open" onClick={() => lb.open(clips, i)} aria-label={`Play clip ${i + 1}: ${clip.caption ?? label}`}>
              {clip.type === "video" && clip.poster ? (
                // eslint-disable-next-line @next/next/no-img-element -- poster generated by scripts/media.ts
                <img src={clip.poster} alt="" loading="lazy" width={clip.w} height={clip.h} />
              ) : null}
              <span aria-hidden="true">▶</span>
            </button>
          ))}
        </div>
      ) : null}
      <Lightbox lb={lb} />
    </>
  );
}
