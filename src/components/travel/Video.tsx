"use client";

import { useState } from "react";
import type { MediaItem } from "@/lib/content/media";

/** Click-to-play: nothing downloads until the visitor presses play, and nothing autoplays with sound. */
export function ClipPlayer({ clip, label }: { clip: MediaItem; label: string }) {
  const [live, setLive] = useState(false);
  if (clip.type !== "video") return null;
  return live ? (
    <video className="vf-live" src={clip.src} poster={clip.poster || undefined} controls autoPlay playsInline width={clip.w} height={clip.h} aria-label={label} />
  ) : (
    <button className="vf" type="button" onClick={() => setLive(true)} aria-label={`Play clip: ${label}`}>
      {clip.poster ? (
        // eslint-disable-next-line @next/next/no-img-element -- poster generated by scripts/media.ts
        <img src={clip.poster} width={clip.w} height={clip.h} alt="" loading="lazy" />
      ) : null}
      <span className="pl">▶ Play clip</span>
    </button>
  );
}

/** Long-form video from YouTube's privacy-enhanced domain; the player loads only after a click. */
export function YouTube({ id, title }: { id: string; title: string }) {
  const [live, setLive] = useState(false);
  return live ? (
    <iframe
      className="vf-live"
      src={`https://www.youtube-nocookie.com/embed/${encodeURIComponent(id)}?autoplay=1`}
      title={title}
      allow="autoplay; encrypted-media; picture-in-picture"
      allowFullScreen
    />
  ) : (
    <button className="vf" type="button" onClick={() => setLive(true)} aria-label={`Play video: ${title}`}>
      {/* eslint-disable-next-line @next/next/no-img-element -- remote thumbnail */}
      <img src={`https://i.ytimg.com/vi/${encodeURIComponent(id)}/hqdefault.jpg`} alt="" loading="lazy" width={480} height={360} />
      <span className="pl">▶ {title}</span>
    </button>
  );
}
